"""``secdeploy configure --web`` — a tiny local web UI for writing the site config.

Serves ONE SecRouter-themed page (the same palette as the suite's landing page in
``wiring.landing_page_html``) on loopback, with every ``secsite.toml`` option laid out with an
explanation: placement (domain / resources / tier groups), the suite-wide ``[deploy]`` table,
per-resource deploy toggles, declared ``[[users]]``, the ``[secchat.pool]`` options, and the
optional ``[[builds]]`` container builds. Saving round-trips the form through
:meth:`SiteConfig.load`, so the page enforces exactly the same fail-loud validation as the CLI —
errors render inline and nothing is written until the config is valid.

Design notes:

* Pure standard library (``http.server`` + ``urllib.parse``), matching the rest of secdeploy —
  no framework, no CDN, inline CSS/JS only, bound to 127.0.0.1.
* The per-resource/pool/build sections are generated by REFLECTION over the dataclasses
  (:class:`DeployOptions`, :class:`PoolOptions`, :class:`BuildSpec`), with a hand-written help
  text per known field — so a new option added to those classes shows up here automatically
  (with its field name as a placeholder explanation until help is written).
* Validation is a round trip: form → TOML text → ``SiteConfig.load`` → on error, re-render the
  form with the submitted values + the errors; on success, write the destination (or a named
  profile — see ``sites/``) and show the saved banner.
"""

