# ── form → TOML → SiteConfig ───────────────────────────────────────────────────────────────────

def _rows(form: dict[str, list[str]], prefix: str) -> list[dict[str, str]]:
    """Collect indexed row fields (`res.0.name`, `res.0.address`, …) into per-row dicts, in index
    order, skipping rows whose every value is blank (a removed/empty template row)."""
    rows: dict[int, dict[str, str]] = {}
    for key, values in form.items():
        parts = key.split(".", 2)
        if len(parts) != 3 or parts[0] != prefix or not parts[1].isdigit():
            continue
        rows.setdefault(int(parts[1]), {})[parts[2]] = values[0]
    out = []
    for idx in sorted(rows):
        if any(v.strip() for v in rows[idx].values()):
            out.append(rows[idx])
    return out


def _toml_str(v: str) -> str:
    return json.dumps(v)  # JSON string escaping is valid TOML for our ASCII-ish config values


def _toml_list(csv: str) -> str:
    items = [i.strip() for i in csv.split(",") if i.strip()]
    return "[" + ", ".join(_toml_str(i) for i in items) + "]"


def form_to_toml(form: dict[str, list[str]]) -> str:
    """Assemble the submitted form into secsite.toml text (validated separately via
    SiteConfig.load — this only SHAPES the data)."""

    def val(key: str, default: str = "") -> str:
        return form.get(key, [default])[0].strip()

    def flag(key: str) -> bool:
        return key in form  # checkboxes submit only when checked

    lines: list[str] = [f"domain = {_toml_str(val('domain'))}"]
    if val("upstream_dns"):
        lines.append(f"upstream_dns = {_toml_list(val('upstream_dns'))}")
    without = [v for v in form.get("without", [])]
    lines += ["", "[deploy]"]
    if without:
        lines.append("without = [" + ", ".join(_toml_str(w) for w in without) + "]")
    if flag("ssh"):
        lines.append("ssh = true")

    bool_res_keys = {"with_inference", "with_agent", "configure_resolver", "tls",
                     "configure_hosts", "trust_ca"}
    for row in _rows(form, "res"):
        name = row.get("name", "").strip()
        lines += ["", f"[resources.{name}]"]
        lines.append(f"target = {_toml_str(row.get('target', 'macos'))}")
        lines.append(f"address = {_toml_str(row.get('address', ''))}")
        if row.get("capabilities", "").strip():
            lines.append(f"capabilities = {_toml_list(row['capabilities'])}")
        for k in sorted(bool_res_keys):
            if row.get(k):  # checkbox present = on
                lines.append(f"{k} = true")
        if row.get("model_dir", "").strip():
            lines.append(f"model_dir = {_toml_str(row['model_dir'].strip())}")
        if row.get("autostart_models", "").strip():
            lines.append(f"autostart_models = {_toml_list(row['autostart_models'])}")
        backend = row.get("inference_backend", "").strip()
        if backend and backend != "auto":
            lines.append(f"inference_backend = {_toml_str(backend)}")

    for tier in TIERS:
        targets = val(f"group.{tier}")
        if targets:
            names = [t.strip() for t in targets.split(",") if t.strip()]
            lines += ["", f"[groups.{tier}]"]
            if len(names) == 1:
                lines.append(f"resource = {_toml_str(names[0])}")
            else:
                lines.append("resources = [" + ", ".join(_toml_str(n) for n in names) + "]")

    for row in _rows(form, "user"):
        lines += ["", "[[users]]"]
        lines.append(f"username = {_toml_str(row.get('username', '').strip())}")
        lines.append(f"email = {_toml_str(row.get('email', '').strip())}")
        lines.append(f"name = {_toml_str(row.get('name', '').strip())}")
        lines.append(f"groups = {_toml_list(row.get('groups', ''))}")

    if flag("pool.enabled"):
        lines += ["", "[secchat.pool]", "enabled = true"]
        analysis_lines: list[str] = []
        for f in dataclasses.fields(PoolOptions):
            if f.name == "enabled":
                continue
            key = f"pool.{f.name}"
            if f.name == "analysis_images":
                for entry in val(key).splitlines():
                    if "=" in entry:
                        n, _, img = entry.partition("=")
                        if n.strip() and img.strip():
                            analysis_lines.append(f"{n.strip()} = {_toml_str(img.strip())}")
                continue
            if _widget_kind(f) == "bool":
                if flag(key):
                    lines.append(f"{f.name} = true")
            elif _widget_kind(f) == "number":
                if val(key):
                    lines.append(f"{f.name} = {int(val(key))}")
            elif val(key):
                lines.append(f"{f.name} = {_toml_str(val(key))}")
        if analysis_lines:
            lines += ["", "[secchat.pool.analysis_images]", *analysis_lines]

    for row in _rows(form, "build"):
        lines += ["", "[[builds]]"]
        for f in dataclasses.fields(BuildSpec):
            v = row.get(f.name, "")
            if _widget_kind(f) == "bool":
                if v:
                    lines.append(f"{f.name} = true")
            elif v.strip():
                lines.append(f"{f.name} = {_toml_str(v.strip())}")

    return "\n".join(lines) + "\n"


def validate_form(form: dict[str, list[str]], manifest: Manifest,
                  tmp_dir: Path) -> tuple[SiteConfig | None, str, list[str]]:
    """form → TOML → SiteConfig.load. Returns (site|None, toml_text, errors) — the SAME fail-loud
    validation the CLI applies, surfaced back onto the page."""
    text = form_to_toml(form)
    tmp = tmp_dir / "webconfig-candidate.toml"
    tmp.write_text(text)
    try:
        return SiteConfig.load(tmp, manifest), text, []
    except ValueError as exc:
        return None, text, str(exc).splitlines()
    finally:
        tmp.unlink(missing_ok=True)


# ── the server ─────────────────────────────────────────────────────────────────────────────────

def serve(manifest: Manifest, dest: str, port: int = DEFAULT_PORT,
          open_browser: bool = True) -> None:
    """Serve the configurator on 127.0.0.1:``port`` until interrupted. GET / renders the form
    (prefilled from ``dest`` when it loads); POST /save validates + writes."""
    import tempfile

    dest_path = Path(dest)

    def initial_site() -> SiteConfig:
        if dest_path.exists():
            try:
                return SiteConfig.load(dest_path, manifest)
            except ValueError:
                pass  # unparseable current file — start from a blank form rather than crash
        return SiteConfig.single_host(manifest, "macos")

    class Handler(BaseHTTPRequestHandler):
        def _page(self, body: str, status: int = 200) -> None:
            data = body.encode()
            self.send_response(status)
            self.send_header("content-type", "text/html; charset=utf-8")
            self.send_header("content-length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self):
            if self.path not in ("/", "/index.html"):
                self.send_response(404)
                self.end_headers()
                return
            self._page(render_form(initial_site(), manifest, dest))

        def do_POST(self):
            if self.path != "/save":
                self.send_response(404)
                self.end_headers()
                return
            length = int(self.headers.get("content-length", "0"))
            form = parse_qs(self.rfile.read(length).decode(), keep_blank_values=True)
            with tempfile.TemporaryDirectory() as td:
                site, text, errors = validate_form(form, manifest, Path(td))
            if errors:
                self._page(render_form(initial_site(), manifest, dest, errors=errors), 422)
                return
            save_as = form.get("save_as", [""])[0].strip()
            target = site_profile_path(save_as) if save_as and "/" not in save_as else \
                Path(save_as) if save_as else dest_path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
            self._page(render_form(site, manifest, dest, saved=str(target)))  # type: ignore[arg-type]

        def log_message(self, *args):  # quiet — this is a local tool, not a service
            pass

    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    url = f"http://127.0.0.1:{port}/"
    print(f"secdeploy configure --web: {url}  (Ctrl-C to stop)")
    if open_browser:
        threading.Timer(0.3, lambda: webbrowser.open(url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nstopped")
    finally:
        server.server_close()
