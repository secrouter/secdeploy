def _esc(s: object) -> str:
    return html.escape(str(s), quote=True)


def _help(key: str) -> str:
    return HELP.get(key, key.rsplit(".", 1)[-1].replace("_", " "))


def _input(name: str, value: object, help_key: str, kind: str = "text") -> str:
    """One labeled form control with its explanation line."""
    label = help_key.rsplit(".", 1)[-1].replace("_", " ")
    if kind == "bool":
        checked = " checked" if value else ""
        control = (f'<label class="chk"><input type="checkbox" name="{_esc(name)}"{checked}> '
                   f"{_esc(label)}</label>")
        return f'<div class="field">{control}<p class="help">{_esc(_help(help_key))}</p></div>'
    if kind == "number":
        control = f'<input type="number" name="{_esc(name)}" value="{_esc(value)}">'
    elif kind == "textarea":
        control = f'<textarea name="{_esc(name)}" rows="3">{_esc(value)}</textarea>'
    else:
        control = f'<input type="text" name="{_esc(name)}" value="{_esc(value)}">'
    return (f'<div class="field"><label>{_esc(label)}</label>{control}'
            f'<p class="help">{_esc(_help(help_key))}</p></div>')


def _widget_kind(f: dataclasses.Field) -> str:
    if f.type in ("bool", bool):
        return "bool"
    if f.type in ("int", int):
        return "number"
    return "text"


def _dataclass_fields(obj, section: str, prefix: str, skip: set[str] | None = None) -> str:
    """Reflection-driven controls for every field of a dataclass instance. Dict fields render as
    a name=image-per-line textarea; list[str] fields as comma-joined text."""
    out: list[str] = []
    for f in dataclasses.fields(obj):
        if skip and f.name in skip:
            continue
        value = getattr(obj, f.name)
        key = f"{section}.{f.name}"
        name = f"{prefix}{f.name}"
        if isinstance(value, dict):
            text = "\n".join(f"{k}={v}" for k, v in sorted(value.items()))
            out.append(_input(name, text, key, "textarea"))
        elif isinstance(value, list):
            out.append(_input(name, ", ".join(str(v) for v in value), key))
        elif isinstance(value, bool):
            out.append(_input(name, value, key, "bool"))
        elif isinstance(value, int):
            out.append(_input(name, value, key, "number"))
        else:
            out.append(_input(name, value, key))
    return "\n".join(out)


